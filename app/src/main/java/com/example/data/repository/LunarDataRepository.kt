    /**
     * Generate synthetic rover telemetry ticks along the selected route.
     */
    fun simulateTelemetryStep(
        elapsedHours: Double,
        spec: RoverSpecification = RoverSpecification()
    ): RoverTelemetryState {
        val clampedHours = elapsedHours.coerceIn(0.0, 72.0)
        val progressFraction = (clampedHours / 72.0).coerceIn(0.0, 1.0)
        val psrEntryFraction = 0.65
        val psrEntryHours = 72.0 * psrEntryFraction
        val isPsr = progressFraction > psrEntryFraction

        val currentSlope = if (isPsr) 9.8 else 8.4 + (progressFraction * 4.0)
        val currentTemp = if (isPsr) 44.0 else 185.0 - (progressFraction * 60.0)
        val totalDistanceKm = progressFraction * 14.8

        // Energy calculations (cumulative, monotonic solar PV recharge on sunlit ridge prior to PSR entry)
        val locomotionHours = clampedHours * 0.38
        val locomotionEnergy = locomotionHours * (spec.locomotionPowerWatts / 1000.0)

        val heatingHours = max(0.0, clampedHours - psrEntryHours)
        val heatingEnergy = heatingHours * (spec.psrThermalHeaterWatts / 1000.0)

        val commsHours = clampedHours * 0.65 // Duty-cycled X/Ka-band DTE windows
        val commsEnergy = commsHours * (spec.commsPowerWatts / 1000.0)

        val drillFraction = ((progressFraction - 0.80) / 0.20).coerceIn(0.0, 1.0)
        val drillEnergy = drillFraction * 3.0 * (spec.drillPowerWatts / 1000.0)

        val processFraction = ((progressFraction - 0.90) / 0.10).coerceIn(0.0, 1.0)
        val processEnergy = processFraction * 6.5 * (spec.volatileProcessingPowerWatts / 1000.0)

        // Solar charging accumulates only while traversing the sunlit Connecting Ridge (0..46.8h)
        // Average effective charging factor 0.405 accounts for 86% illumination & incidence angle
        val sunlitElapsedHours = min(clampedHours, psrEntryHours)
        val solarRecharge = sunlitElapsedHours * 0.405 * (spec.solarPvPeakPowerWatts / 1000.0)

        val netExpended = locomotionEnergy + heatingEnergy + commsEnergy + drillEnergy + processEnergy
        val remainingBattery = max(
            0.0,
            min(100.0, ((spec.batteryCapacityKWh - netExpended + solarRecharge) / spec.batteryCapacityKWh) * 100.0)
        )

        val breakdown = EnergyBudgetBreakdown(
            locomotionKWh = locomotionEnergy,
            cryogenicHeatingKWh = heatingEnergy,
            communicationsKWh = commsEnergy,
            coreDrillingKWh = drillEnergy,
            volatileProcessingKWh = processEnergy,
            returnReserveKWh = spec.batteryCapacityKWh * (spec.minReturnReservePercent / 100.0),
            solarRechargeKWh = solarRecharge,
            netEnergyUsedKWh = netExpended,
            remainingBatteryPercent = remainingBattery
        )

        return RoverTelemetryState(
            elapsedHours = clampedHours,
            currentLat = -89.45 - (progressFraction * 0.45),
            currentLon = -122.50 + (progressFraction * 122.50),
            currentElevationM = -820.0 - (progressFraction * 3380.0),
            currentSlopeDeg = currentSlope,
            currentTempKelvin = currentTemp,
            isInsidePsr = isPsr,
            batterySoCPercent = remainingBattery,
            totalDistanceTraveledKm = totalDistanceKm,
            earthLosStatus = !isPsr || progressFraction < 0.9,
            energyBreakdown = breakdown,
            accumulatedVolatilesKg = if (progressFraction > 0.85) (progressFraction - 0.85) * 80.0 else 0.0
        )
    }

    private fun fmt1(value: Double): String {
        val tenths = (value * 10.0).roundToInt()
        val absTenths = kotlin.math.abs(tenths)
        val whole = absTenths / 10
        val frac = absTenths % 10
        return if (tenths < 0) "-$whole.$frac" else "$whole.$frac"
    }

    /**
     * Dynamic evaluation of route safety against variable geotechnical slope limits and battery reserve thresholds.
     * Demonstrates live how route decisions change based on engineering constraints.
     */
    fun evaluateDynamicRouteConstraints(
        slopeLimitDeg: Double,
        minBatteryReservePercent: Double
    ): DynamicConstraintComparison {
        val comparison = getFocusMissionRouteComparison()
        val opt = comparison.optimizedRoute
        val base = comparison.baselineRoute

        // 1. Proposed Ridge Route (14.8 km)
        val optSlopePassed = opt.maxSlopeDeg <= slopeLimitDeg
        val optBatteryPassed = opt.netBatteryRemainingPercent >= minBatteryReservePercent
        val optFeasible = optSlopePassed && optBatteryPassed
        val optFailure = when {
            !optSlopePassed && !optBatteryPassed -> "Max slope (${fmt1(opt.maxSlopeDeg)}°) exceeds ${fmt1(slopeLimitDeg)}° AND battery (${fmt1(opt.netBatteryRemainingPercent)}%) < ${fmt1(minBatteryReservePercent)}% reserve"
            !optSlopePassed -> "Max slope (${fmt1(opt.maxSlopeDeg)}°) exceeds ${fmt1(slopeLimitDeg)}° constraint"
            !optBatteryPassed -> "Battery at target (${fmt1(opt.netBatteryRemainingPercent)}%) falls below ${fmt1(minBatteryReservePercent)}% reserve"
            else -> null
        }
        val optAssessment = RouteSafetyAssessment(
            routeName = "Proposed Ridge Route (14.8 km)",
            distanceKm = opt.totalDistanceKm,
            maxSlopeDeg = opt.maxSlopeDeg,
            slopePassed = optSlopePassed,
            slopeMarginDeg = slopeLimitDeg - opt.maxSlopeDeg,
            returnBatteryPercent = opt.netBatteryRemainingPercent,
            batteryPassed = optBatteryPassed,
            batteryMarginPercent = opt.netBatteryRemainingPercent - minBatteryReservePercent,
            isOverallFeasible = optFeasible,
            primaryFailureReason = optFailure,
            decisionLabel = if (optFeasible) "APPROVED FOR TRAVERSE" else "CONSTRAINED: FAILS SETTINGS"
        )

        // 2. Direct Euclidean Baseline (9.2 km)
        val baseSlopePassed = base.maxSlopeDeg <= slopeLimitDeg
        val baseBatteryPassed = base.netBatteryRemainingPercent >= minBatteryReservePercent
        val baseFeasible = baseSlopePassed && baseBatteryPassed
        val baseFailure = when {
            !baseSlopePassed && !baseBatteryPassed -> "Crater wall slope ${fmt1(base.maxSlopeDeg)}° > ${fmt1(slopeLimitDeg)}° limit AND return battery ${fmt1(base.netBatteryRemainingPercent)}% < ${fmt1(minBatteryReservePercent)}% reserve"

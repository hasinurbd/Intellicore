            else -> null
        }
        val baseAssessment = RouteSafetyAssessment(
            routeName = "Direct Euclidean Route (9.2 km)",
            distanceKm = base.totalDistanceKm,
            maxSlopeDeg = base.maxSlopeDeg,
            slopePassed = baseSlopePassed,
            slopeMarginDeg = slopeLimitDeg - base.maxSlopeDeg,
            returnBatteryPercent = base.netBatteryRemainingPercent,
            batteryPassed = baseBatteryPassed,
            batteryMarginPercent = base.netBatteryRemainingPercent - minBatteryReservePercent,
            isOverallFeasible = baseFeasible,
            primaryFailureReason = baseFailure,
            decisionLabel = if (baseFeasible) "CONDITIONALLY TOLERATED (Unrealistic Limits)" else "REJECTED: CRITICAL RISK"
        )

        val summary = when {
            optFeasible && !baseFeasible ->
                "At ${fmt1(slopeLimitDeg)}° slope limit and ${fmt1(minBatteryReservePercent)}% return reserve, the Proposed 14.8 km Route is the ONLY viable path. The Direct 9.2 km route is rejected because: ${baseFailure}."
            optFeasible && baseFeasible ->
                "CAUTION: Direct 9.2 km route only appears feasible because slope limit was relaxed to ${fmt1(slopeLimitDeg)}° (exceeding regolith internal friction angle) and reserve relaxed to ${fmt1(minBatteryReservePercent)}%."
            !optFeasible && !baseFeasible ->
                "CRITICAL: Both routes fail under current tight constraints (Slope limit ${fmt1(slopeLimitDeg)}°, Reserve ${fmt1(minBatteryReservePercent)}%). Rover cannot reach Shackleton PSR under these conditions."
            else ->
                "Alternative traversal profile active under custom simulation parameters."
        }

        return DynamicConstraintComparison(
            slopeLimitDeg = slopeLimitDeg,
            minBatteryReservePercent = minBatteryReservePercent,
            proposedRouteAssessment = optAssessment,
            directRouteAssessment = baseAssessment,
            recommendationSummary = summary
        )
    }


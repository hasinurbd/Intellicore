    /**
     * Compute Mining Viability Index (MVI) transparently.
     * Score is relative suitability (0-100) under specified weights, NOT a % probability.
     */
    fun calculateMvi(site: ResourcePoint, weights: MviWeights = MviWeights()): MviEvaluation {
        val norm = weights.normalized()

        // 1. Resource Subscore (0-100): Based on hydrogen enrichment proxy & mineral potential
        val hScore = (site.hydrogenEnrichmentPpm / 700.0).coerceIn(0.0, 1.0) * 80.0
        val minScore = (site.ilmeniteMineralWtPercent / 5.0).coerceIn(0.0, 1.0) * 20.0
        val sResource = hScore + minScore

        // 2. Slope Accessibility Subscore (0-100): Hard penalty at 18° geotechnical threshold
        val sSlope = when {
            site.slopeDegrees <= 8.0 -> 100.0
            site.slopeDegrees <= 14.0 -> 100.0 - (site.slopeDegrees - 8.0) * 8.0 // 100 -> 52
            site.slopeDegrees <= 18.0 -> 52.0 - (site.slopeDegrees - 14.0) * 10.0 // 52 -> 12
            else -> 0.0 // Exceeds geotechnical stability limit (>18°)
        }

        // 3. Extraction Feasibility (0-100): Based on surface roughness and regolith compaction
        val sExtraction = ((1.0 - site.surfaceRoughnessIndex) * 100.0).coerceIn(10.0, 100.0)

        // 4. Solar Illumination Availability (0-100)
        val sSolar = site.solarIlluminationPercent

        // 5. Thermal Embrittlement Penalty (0-100):
        // Metallic alloys and elastomers experience cryogenic ductile-to-brittle transition (DBTT) below 50K
        val isEmbrittled = site.minDiurnalTempKelvin < 50.0
        val pThermal = if (isEmbrittled) {
            // Severe penalty scaling exponentially as temperature drops below 50K
            ((50.0 - site.minDiurnalTempKelvin) / 50.0 * 100.0).coerceIn(40.0, 100.0)
        } else {
            0.0
        }

        // 6. Direct-to-Earth Communication Line-of-Sight (0-100)
        val sComm = site.earthLineOfSightPercent

        // 7. Distance / Topographical Penalty (0-100)
        val pDistance = if (site.elevationMeters < -3000) 40.0 else 10.0

        // Final transparent linear weighted combination
        val rawScore = (norm.resourcePotential * sResource) +
                (norm.slopeAccessibility * sSlope) +
                (norm.extractionFeasibility * sExtraction) +
                (norm.solarIllumination * sSolar) -
                (norm.thermalEmbrittlement * pThermal) +
                (norm.commLineOfSight * sComm) -
                (norm.traverseDistance * pDistance)

        val totalScore = rawScore.coerceIn(0.0, 100.0)

        return MviEvaluation(
            siteId = site.id,
            siteName = site.name,
            totalScore = totalScore,
            resourceSubscore = sResource,
            slopeSubscore = sSlope,
            extractionSubscore = sExtraction,
            solarSubscore = sSolar,
            thermalPenalty = pThermal,
            commSubscore = sComm,
            distancePenalty = pDistance,
            weightsUsed = norm,
            isCryogenicEmbrittlementRisk = isEmbrittled,
            minTempKelvin = site.minDiurnalTempKelvin,
            slopeDegrees = site.slopeDegrees
        )
    }

